"""Create synthetic CCU-Historian-like H2 databases for testing.

The schema imitates the CCU-Historian layout (DATA_POINTS + one table
D_<IF>_<ADDR>_<IDENT> per data point with TS/VALUE/STATE). It is NOT a byte
exact copy of the real schema.
"""
from __future__ import annotations

import glob
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from historian_repair import h2engine as E  # noqa: E402

DPS = [
    ("BidCos-RF", "LEQ0000001:1", "TEMPERATURE", "Wohnzimmer Temp", False),
    ("BidCos-RF", "LEQ0000001:1", "HUMIDITY", "Wohnzimmer Feuchte", False),
    ("HmIP-RF", "000A1B2C3D4E5F:1", "ACTUAL_TEMPERATURE", "Bad Temp", False),
    ("SysVar", "1234", "", "Anwesenheit", True),
    ("HmIP-RF", "000A1B2C3D4E5F:0", "OPERATING_VOLTAGE", "Bad Batterie", False),
]


def create(path_base: str, jar: str, start: str, end: str, step_s: int, dps=DPS,
           gap: tuple[str, str] | None = None, extra_dp=None) -> None:
    drv = E.H2Driver.get(jar)
    for f in glob.glob(path_base + ".*"):
        os.remove(f)
    c = drv.connect(f"jdbc:h2:file:{path_base}", "sa", "")
    c.setAutoCommit(False)
    ident = "INT AUTO_INCREMENT" if drv.v1 else "INT GENERATED BY DEFAULT AS IDENTITY"
    E.execute(c, f'CREATE TABLE DATA_POINTS(DP_ID {ident} PRIMARY KEY, INTERFACE VARCHAR NOT NULL, '
                 'ADDRESS VARCHAR NOT NULL, IDENTIFIER VARCHAR NOT NULL, PRESET BOOLEAN, '
                 'DISPLAY_NAME VARCHAR, ROOM VARCHAR, UNIT VARCHAR, HISTORY_STRING BOOLEAN, '
                 'CUSTOM VARCHAR)')
    E.execute(c, 'CREATE TABLE CONFIG(CFG_KEY VARCHAR PRIMARY KEY, CFG_VALUE VARCHAR)')
    E.execute(c, "INSERT INTO CONFIG VALUES('DB_VERSION','3')")
    lo, hi = E.str_to_ms(start), E.str_to_ms(end)
    g0, g1 = (E.str_to_ms(gap[0]), E.str_to_ms(gap[1])) if gap else (None, None)
    allp = list(dps) + ([extra_dp] if extra_dp else [])
    for k, (iface, addr, ident_, name, is_str) in enumerate(allp):
        tn = E.historian_table_name(iface, addr, ident_)
        ps = c.prepareStatement("INSERT INTO DATA_POINTS(INTERFACE,ADDRESS,IDENTIFIER,PRESET,DISPLAY_NAME,"
                                "ROOM,UNIT,HISTORY_STRING) VALUES(?,?,?,?,?,?,?,?)")
        for i, v in enumerate([iface, addr, ident_, False, name, "Raum", "°C", is_str], 1):
            ps.setObject(i, v)
        ps.executeUpdate()
        vt = "VARCHAR" if is_str else "DOUBLE"
        E.execute(c, f'CREATE TABLE {E.q(tn)}(TS TIMESTAMP NOT NULL, "VALUE" {vt}, STATE INT)')
        E.execute(c, f'CREATE INDEX ON {E.q(tn)}(TS)')
        ins = c.prepareStatement(f'INSERT INTO {E.q(tn)} VALUES(?,?,?)')
        t = lo + k * 1000
        n = 0
        while t <= hi:
            if not (g0 is not None and g0 <= t <= g1):
                ins.setTimestamp(1, E.make_ts(t))
                ins.setObject(2, f"s{t // 1000}" if is_str else float((t // 1000) % 1000) / 10)
                ins.setObject(3, 0)
                ins.addBatch()
                n += 1
                if n % 10000 == 0:
                    ins.executeBatch()
            t += step_s * 1000
        ins.executeBatch()
    c.commit()
    E.execute(c, "SHUTDOWN COMPACT")
    c.close()


if __name__ == "__main__":
    E.start_jvm()
    jar, out = sys.argv[1], sys.argv[2]
    create(out, jar, "2024-01-01", "2024-02-01", 300)
